def save_checkpoint(path, epoch, model, disc, opt_main, opt_disc,
                    warmup_sched, cosine_sched, swa_model, swa_sched,
                    best_auroc, wait, history, swa_active):
    torch.save({
        "epoch": epoch,
        "model": model.state_dict(),
        "disc":  disc.state_dict(),
        "opt_main":     opt_main.state_dict(),
        "opt_disc":     opt_disc.state_dict(),
        "warmup_sched": warmup_sched.state_dict() if warmup_sched else None,
        "cosine_sched": cosine_sched.state_dict() if cosine_sched else None,
        "swa_model":    swa_model.state_dict()    if swa_model   else None,
        "swa_sched":    swa_sched.state_dict()    if swa_sched   else None,
        "best_auroc": best_auroc,
        "wait":       wait,
        "history":    history,
        "swa_active": swa_active,
    }, path)

    mirror_to_drive(path)

def load_checkpoint(path, model, disc, opt_main, opt_disc,
                    warmup_sched, cosine_sched, swa_model, swa_sched):
    restore_from_drive(path)

    ckpt = torch.load(path, map_location=device)
    model.load_state_dict(ckpt["model"])
    disc.load_state_dict(ckpt["disc"])
    opt_main.load_state_dict(ckpt["opt_main"])
    opt_disc.load_state_dict(ckpt["opt_disc"])

    if ckpt.get("warmup_sched") and warmup_sched:
        warmup_sched.load_state_dict(ckpt["warmup_sched"])
    if ckpt.get("cosine_sched") and cosine_sched:
        cosine_sched.load_state_dict(ckpt["cosine_sched"])
    if ckpt.get("swa_model") and swa_model:
        swa_model.load_state_dict(ckpt["swa_model"])
    if ckpt.get("swa_sched") and swa_sched:
        swa_sched.load_state_dict(ckpt["swa_sched"])

    return (
        ckpt["epoch"] + 1,
        ckpt.get("best_auroc", -1.0),
        ckpt.get("wait", 0),
        ckpt.get("history", {"loss": [], "val_auroc": [], "val_auprc": []}),
        ckpt.get("swa_active", False),
    )

def save_best_model(path, model, disc, th):
    torch.save({
        "model": model.state_dict(),
        "disc":  disc.state_dict(),
        "th":    th
    }, path)
    mirror_to_drive(path)


def run_one_seed(seed: int) -> dict:
    seed_everything(seed)

    print(f"\n{'=' * 70}")
    print(f"SEED {seed}  —  BindingDB DTI VAE-GAN v4")
    print(f"{'=' * 70}")

    NUM_EPOCHS    = 120
    PATIENCE      = 25
    LR            = 3e-5
    LR_DISC       = 1e-4
    WEIGHT_DECAY  = 1e-3
    W_KL          = 0.02
    W_REC         = 0.3
    W_CON         = 0.2
    W_ADV         = 0.5
    GRAD_ACCUM    = 4
    SWA_START     = 45
    SWA_LR        = 5e-6
    WARMUP_EPOCHS = 15

    seed_dir = os.path.join(SAVE_DIR, f"seed_{seed}")
    os.makedirs(seed_dir, exist_ok=True)

    best_path   = os.path.join(seed_dir, "best_model.pth")
    latest_path = os.path.join(seed_dir, "checkpoint_latest.pth")

    restore_from_drive(latest_path)
    restore_from_drive(best_path)

    train_loader, valid_loader, test_loader = get_loaders(batch_size=8)

    model = CrossAttnVAE(d_model=768, latent_dim=256,
                         drug_unfreeze=2, prot_unfreeze=2).to(device)
    disc  = Discriminator(input_dim=768, hidden_dim=512).to(device)

    loss_fn = AsymmetricFocalLoss(pos_weight=None, gamma_pos=0.0,
                                  gamma_neg=4.0, label_smoothing=0.01, clip=0.05)

    pretrained_ids = (
        set(id(p) for p in model.drug_encoder.bert.parameters()) |
        set(id(p) for p in model.protein_node_encoder.encoder.parameters())
    )
    main_pretrained = [p for p in model.parameters()
                       if p.requires_grad and id(p) in pretrained_ids]
    main_new        = [p for p in model.parameters()
                       if p.requires_grad and id(p) not in pretrained_ids]

    opt_main = torch.optim.AdamW(
        [{"params": main_pretrained, "lr": LR * 0.1},
         {"params": main_new,        "lr": LR}],
        weight_decay=WEIGHT_DECAY
    )
    opt_disc = torch.optim.AdamW(disc.parameters(), lr=LR_DISC,
                                 betas=(0.5, 0.999), weight_decay=1e-4)

    swa_model  = AveragedModel(model)
    swa_sched  = SWALR(opt_main, swa_lr=SWA_LR, anneal_epochs=5)
    swa_active = False

    warmup_sched = torch.optim.lr_scheduler.LambdaLR(
        opt_main, lr_lambda=lambda ep: min(1.0, (ep + 1) / WARMUP_EPOCHS))
    cosine_sched = torch.optim.lr_scheduler.CosineAnnealingWarmRestarts(
        opt_main, T_0=20, T_mult=1, eta_min=1e-7)

    def step_scheduler(epoch):
        if epoch >= SWA_START:
            return
        elif epoch < WARMUP_EPOCHS:
            warmup_sched.step()
        else:
            cosine_sched.step(epoch - WARMUP_EPOCHS)

    start_epoch = 1
    best_auroc  = -1.0
    wait        = 0
    history     = {"loss": [], "val_auroc": [], "val_auprc": []}

    if os.path.exists(latest_path):
        print(f"  Resuming from checkpoint: {latest_path}")
        start_epoch, best_auroc, wait, history, swa_active = load_checkpoint(
            latest_path, model, disc, opt_main, opt_disc,
            warmup_sched, cosine_sched, swa_model, swa_sched)
        print(f"  Resumed at epoch {start_epoch}, best_auroc={best_auroc:.4f}, wait={wait}")
    else:
        print("  Starting fresh.")

    for ep in range(start_epoch, NUM_EPOCHS + 1):
        tr_loss = train_one_epoch(
            model, disc, train_loader, opt_main, opt_disc, loss_fn,
            w_kl=W_KL, w_rec=W_REC, w_con=W_CON, w_adv=W_ADV,
            grad_accum_steps=GRAD_ACCUM, mixup_alpha=0.4, p_mixup=0.5)

        if ep >= SWA_START:
            swa_model.update_parameters(model)
            swa_sched.step()
            swa_active = True

        valid_m = evaluate_best_th(model, valid_loader)
        history["loss"].append(tr_loss)
        history["val_auroc"].append(valid_m["AUROC"])
        history["val_auprc"].append(valid_m["AUPRC"])

        print(
            f"  [S{seed}] Ep {ep:03d} | Loss {tr_loss:.4f} | "
            f"AUROC {valid_m['AUROC']:.4f}  AUPRC {valid_m['AUPRC']:.4f}  "
            f"F1 {valid_m['F1']:.4f}  TH {valid_m['TH']:.3f}"
            + ("  [SWA]" if swa_active else "")
        )

        if valid_m["AUROC"] > best_auroc:
            best_auroc = valid_m["AUROC"]
            save_best_model(best_path, model, disc, valid_m["TH"])
            wait = 0
            print("    ✓ Saved best model locally + Drive")
        else:
            wait += 1

        save_checkpoint(
            latest_path, ep, model, disc, opt_main, opt_disc,
            warmup_sched, cosine_sched, swa_model, swa_sched,
            best_auroc, wait, history, swa_active)

        if wait >= PATIENCE:
            print(f"  Early stopping at epoch {ep}")
            break

        step_scheduler(ep - 1)

    if swa_active:
        print("  Updating SWA batch-norm stats...")
        update_bn(train_loader, swa_model, device=device)

    restore_from_drive(best_path)
    ckpt = torch.load(best_path, map_location=device)

    best_model = CrossAttnVAE(d_model=768, latent_dim=256,
                              drug_unfreeze=2, prot_unfreeze=2).to(device)
    best_model.load_state_dict(ckpt["model"])

    val_true,  val_logit  = evaluate_logits(best_model, valid_loader)
    test_true, test_logit = evaluate_logits(best_model, test_loader)
    test_logit_cal = platt_calibrate(val_logit, val_true, test_logit)

    val_logit_cal = platt_calibrate(val_logit, val_true, val_logit)
    y_prob_val = sigmoid_np(val_logit_cal)
    prec_v, rec_v, th_v = precision_recall_curve(val_true, y_prob_val)
    f1_v   = 2 * prec_v[:-1] * rec_v[:-1] / (prec_v[:-1] + rec_v[:-1] + 1e-8)
    th_cal = float(th_v[int(np.argmax(f1_v))])

    test_m_cal = compute_metrics(test_true, test_logit_cal, th=th_cal)

    if swa_active:
        ens_true, ens_logit  = ensemble_logits(swa_model.module, best_model,
                                               test_loader, weight_a=0.6)
        _, val_logit_swa     = evaluate_logits(swa_model.module, valid_loader)
        val_ens_logit        = 0.6 * val_logit_swa + 0.4 * val_logit
        ens_logit_cal        = platt_calibrate(val_ens_logit, val_true, ens_logit)

        y_prob_ens = sigmoid_np(ens_logit_cal)
        prec_e, rec_e, th_e = precision_recall_curve(ens_true, y_prob_ens)
        f1_e   = 2 * prec_e[:-1] * rec_e[:-1] / (prec_e[:-1] + rec_e[:-1] + 1e-8)
        th_ens = float(th_e[int(np.argmax(f1_e))])
        final_m = compute_metrics(ens_true, ens_logit_cal, th=th_ens)
    else:
        final_m = test_m_cal

    history_path = os.path.join(seed_dir, "history.json")
    with open(history_path, "w") as f:
        json.dump(history, f)
    mirror_to_drive(history_path)

    show = ["AUROC", "AUPRC", "F1", "ACC", "MCC", "SENS", "SPEC"]
    print(f"  Seed {seed} RESULT: " +
          "  ".join(f"{k} {final_m[k]:.4f}" for k in show))

    return final_m


