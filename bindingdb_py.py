def md5(s: str) -> str:
    return hashlib.md5(s.encode("utf-8")).hexdigest()

@torch.no_grad()
def esm2_embed_sequence(seq: str, max_len: int = 1200,
                        k: int = 3, use_cache: bool = True):
    seq_clean = (seq or "").replace(" ", "").upper()[:max_len]
    if len(seq_clean) == 0:
        return (
            torch.zeros((max_len, ESM_DIM), dtype=torch.float32),
            torch.zeros((max_len, max_len), dtype=torch.bool),
            torch.zeros((max_len,), dtype=torch.float32)
        )

    key   = md5(f"{seq_clean}|L{max_len}|K{k}|esm2_t12_35M")
    fpath = os.path.join(ESM_CACHE_DIR, f"{key}.pt")
    if use_cache and os.path.exists(fpath):
        pack = torch.load(fpath, map_location="cpu")
        return pack["node_feats"], pack["adj"], pack["mask"]

    data = [("protein", seq_clean)]
    _, _, toks = esm_batch_converter(data)
    out  = esm_model(toks.to(device), repr_layers=[esm_model.num_layers])
    rep  = out["representations"][esm_model.num_layers][0, 1:-1, :].detach().cpu()

    L_use      = min(rep.shape[0], max_len)
    node_feats = torch.zeros((max_len, ESM_DIM), dtype=torch.float32)
    node_feats[:L_use] = rep[:L_use]

    mask = torch.zeros((max_len,), dtype=torch.float32)
    mask[:L_use] = 1.0

    adj = torch.zeros((max_len, max_len), dtype=torch.bool)
    for i in range(L_use):
        left, right = max(0, i - k), min(L_use, i + k + 1)
        adj[i, left:right] = True
        adj[i, i] = False

    if use_cache:
        torch.save({"node_feats": node_feats, "adj": adj, "mask": mask}, fpath)

    return node_feats, adj, mask


drug_tok = AutoTokenizer.from_pretrained("seyonec/ChemBERTa-zinc-base-v1")

def clean_smiles(smiles: str) -> str:
    return str(smiles or "").strip().replace(" ", "")

def tokenize_drug_smiles(smiles: str, max_len: int = 128, use_cache: bool = True):
    s = clean_smiles(smiles)
    if not s:
        return (
            torch.zeros((max_len,), dtype=torch.long),
            torch.zeros((max_len,), dtype=torch.long)
        )

    key   = md5(f"{s}|L{max_len}|{getattr(drug_tok, 'name_or_path', 'tok')}")
    fpath = os.path.join(DRUGTOK_CACHE_DIR, f"{key}.pt")
    if use_cache and os.path.exists(fpath):
        pack = torch.load(fpath, map_location="cpu")
        return pack["input_ids"], pack["attention_mask"]

    toks = drug_tok(
        s,
        max_length=max_len,
        padding="max_length",
        truncation=True,
        return_tensors="pt"
    )

    input_ids = toks["input_ids"].squeeze(0).cpu()
    attn_mask = toks["attention_mask"].squeeze(0).cpu()

    if use_cache:
        torch.save({"input_ids": input_ids, "attention_mask": attn_mask}, fpath)

    return input_ids, attn_mask


def _read_csv(path):
    df = pd.read_csv(path)
    df.columns = df.columns.str.strip()
    return df

def standardize_df(df: pd.DataFrame) -> pd.DataFrame:
    drug_col = next((c for c in [
        "SMILES", "smiles", "Drug", "drug",
        "drug_smiles", "compound_iso_smiles",
        "Ligand SMILES",
    ] if c in df.columns), None)

    prot_col = next((c for c in [
        "Target Sequence", "target_seq", "targetseq",
        "Protein", "protein", "sequence", "Sequence",
        "BindingDB Target Chain Sequence",
    ] if c in df.columns), None)

    lab_col = next((c for c in [
        "Label", "label", "Y", "y",
        "interaction", "Interaction",
    ] if c in df.columns), None)

    if None in (drug_col, prot_col, lab_col):
        raise ValueError(
            f"Could not find required columns.\n"
            f"  drug_col={drug_col}, prot_col={prot_col}, lab_col={lab_col}\n"
            f"  Available: {list(df.columns)}"
        )

    out = pd.DataFrame({
        "smiles": df[drug_col].astype(str).str.strip().str.replace(" ", "", regex=False),
        "target_seq": df[prot_col].astype(str).str.strip().str.replace(" ", "", regex=False).str.upper(),
        "label": pd.to_numeric(df[lab_col], errors="coerce"),
    }).dropna()

    out["label"] = out["label"].astype(int)
    out = out[
        (out["smiles"].str.len() > 0) &
        (out["target_seq"].str.len() > 0)
    ].reset_index(drop=True)

    return out

